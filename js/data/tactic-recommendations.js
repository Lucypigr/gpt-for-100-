  function lowProfile(t, self) {
    const d = (self && self.desc) || '';
    if (t.siege >= 16 || (t.siegeG || 0) >= 0.9) return P.siege;
    if (t.role === 'int') {
      if (/恢復|我軍|提高.*我軍|降低.*敵軍/.test(d)) return P.lowInt;
      return P.lowInt;
    }
    if (t.range <= 1 || /受到|防禦|挑釁|援護/.test(d)) return P.lowTank;
    return P.lowPhys;
  }

  function profileFor(t) {
    const self = SKILLS[t.skill];
    const d = (self && self.desc) || '';
    if (t.star <= 3) return lowProfile(t, self);
    if (t.star === 4) {
      if (t.name === '于禁') return P.siege;
      if (t.role === 'int') return /恢復|我軍|降低/.test(d) ? P.support : P.intControl;
      if (t.range <= 1 || /受到|防禦|挑釁|援護/.test(d)) return P.lowTank;
      if (self && self.type === 'pursuit') return P.pursuit;
      return P.lowPhys;
    }
    if (t.role === 'int') {
      if (/恢復|休整|我軍全體.*降低|使我軍|規避/.test(d)) return P.healer;
      if (/混亂|猶豫|怯戰|暴走|降低.*敵軍/.test(d)) return P.intControl;
      if (self && self.type === 'command' && /我軍/.test(d)) return P.support;
      return P.intDps;
    }
    if (self && (self.type === 'pursuit' || /普通攻擊|兩次普通攻擊/.test(d))) return P.pursuit;
    if (/受到.*傷害|挑釁|援護|降低.*傷害/.test(d) && t.range <= 2) return P.tank;
    if (self && self.type === 'active' && /準備/.test(d)) return P.physPrep;
    if (self && self.type === 'active') return P.physActive;
    if (/攻擊.*謀略|策略攻擊/.test(d) && t.int + t.intG * 29 > 140) return P.hybrid;
    return P.physActive;
  }

  function forHero(t) {
    const raw = S[t.name] || profileFor(t);
    const out = [], seen = {};
    for (const r of raw) {
      const sk = skillByName(r.name);
      if (!sk || sk.id === t.skill || seen[sk.id]) continue;
      if (sk.troops && !sk.troops.includes(t.troop)) continue;
      seen[sk.id] = 1;
      out.push({ id: sk.id, name: sk.name, q: sk.q, type: sk.type, reason: r.reason, tier: r.tier });
      if (out.length >= 4) break;
    }
    return out;
  }

  function allCovered() {
    return HEROES.filter(h => h.star >= 3 && h.star <= 5 && !forHero(h).length);
  }

  return { forHero, allCovered, skillByName };
